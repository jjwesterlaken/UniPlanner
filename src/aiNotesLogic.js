/* ---------- mapping AI output onto the app's existing data shapes ----------

   AI notes are stored as a normal `pages` item (the same collection as
   handwritten notebook pages, so folders/future search already cover
   it) plus one `notes` item per term/definition pair (the collection
   the Study cards game already reads). Both collections live inside
   the single `planner_data` JSON blob that syncs in full on every
   change (see 4-BACKEND-GUIDE.md) — AI notes are meaningfully bigger
   than manual notes, so if sync ever gets noticeably slower, splitting
   AI notes into their own table/row is the documented escape hatch,
   not a problem to pre-solve here.
------------------------------------------------------------------- */

/* How much of a failed transcript is kept in the synced planner.

   Transcripts are enormous relative to everything else in the blob: a
   two-hour lecture is roughly 15,000 spoken words, which measures ~88KB
   — forty times a typical notebook page. Storing one whole was a live
   bug, and it fired at the worst moment, when summarising had already
   failed and the user was least able to afford a second problem.

   2000 characters is about 300 words: enough to recognise which lecture
   this is and to see the transcription worked, at ~2KB instead of 88.
   The rest isn't discarded — the full text is still in memory on the
   review screen and is offered as a download (see aiNotes.jsx). What is
   NOT done is silently putting 88KB into a blob that syncs in full on
   every keystroke. */
export const TRANSCRIPT_EXCERPT_CHARS = 2000;

/**
 * The opening of a transcript, cut at a word boundary.
 *
 * Returns what was kept along with the original length, so the caller
 * can tell the user how much more there is rather than leaving them to
 * wonder whether the recording cut out.
 */
export function truncateTranscript(transcript, limit = TRANSCRIPT_EXCERPT_CHARS) {
  const full = typeof transcript === "string" ? transcript : "";
  if (full.length <= limit) {
    return { text: full, truncated: false, fullLength: full.length };
  }
  const slice = full.slice(0, limit);
  const lastSpace = slice.lastIndexOf(" ");
  // Only honour the word boundary if it isn't throwing away a big chunk
  // of the excerpt -- a transcript with no spaces at all shouldn't
  // collapse to nothing.
  const text = lastSpace > limit * 0.8 ? slice.slice(0, lastSpace) : slice;
  return { text, truncated: true, fullLength: full.length };
}

function formatBody({ overview, keyPoints, assessable, openQuestions }) {
  const parts = [overview || ""];
  if (keyPoints && keyPoints.length) {
    parts.push("", "Key points:", ...keyPoints.map((p) => `• ${p}`));
  }
  if (assessable && assessable.length) {
    parts.push("", "Might be assessed:", ...assessable.map((p) => `• ${p}`));
  }
  if (openQuestions && openQuestions.length) {
    parts.push("", "Open questions:", ...openQuestions.map((p) => `• ${p}`));
  }
  return parts.join("\n");
}

/**
 * Pure mapper from the Edge Function's structured result to the two
 * kinds of items the app already knows how to render, sync and study.
 */
export function mapAiResultToItems({ result, course, week, language, uid, nowISO }) {
  const title = `${course || "Lecture"} — Week ${week || "?"} notes`;

  if (result.summaryFailed) {
    const excerpt = truncateTranscript(result.transcript);
    const header = "Transcript (AI summary failed — you can re-run summarizing later or edit this by hand):";
    // No aiMeta on this page, deliberately. aiMeta routes a page to the
    // AI viewer, which is read-only; this one has to open in the normal
    // editor so "edit this by hand" is actually possible.
    return {
      pageItem: {
        id: uid(),
        title,
        body: excerpt.truncated
          ? `${header}\n\n${excerpt.text}\n\n[Only the first ${excerpt.text.length.toLocaleString()} characters are saved here, of ${excerpt.fullLength.toLocaleString()}. Download the full transcript from the recording screen before you leave it — it isn't kept afterwards.]`
          : `${header}\n\n${excerpt.text}`,
        html: "",
        strokes: [],
        style: "lined",
        kind: "text",
        font: "sans",
        folderId: null,
      },
      noteItems: [],
    };
  }

  const translations = { en: result.original };
  if (result.translated && language) translations[language] = result.translated;

  return {
    pageItem: {
      id: uid(),
      title,
      body: formatBody(result.original),
      html: "",
      strokes: [],
      style: "lined",
      kind: "text",
      font: "sans",
      folderId: null,
      aiMeta: {
        course,
        week,
        generatedAt: nowISO(),
        activeLanguage: "en",
        translations,
      },
    },
    noteItems: (result.original.terms || []).map((t) => ({
      id: uid(),
      course,
      week,
      term: t.term,
      content: t.content,
    })),
  };
}

/* ---------- recording state machine ----------

   idle -> requesting -> recording <-> paused -> stopped -> uploading -> review -> saving -> done
                  \-> error (mic denied, blob never existed)
                                            uploading/saving -> error (blob PRESERVED — retry doesn't lose the recording)

   `blob` is only ever cleared by "discard" or "saved" — every error/
   retry transition leaves it untouched, which is what makes "a failed
   transcription doesn't lose the user's recording" a property of the
   reducer rather than a manual QA claim.
------------------------------------------------------------------- */

export const INITIAL_RECORDER_STATE = {
  status: "idle",
  blob: null,
  mimeType: null,
  idempotencyKey: null,
  estimatedDurationSeconds: 0,
  path: null,
  result: null,
  errorCode: null,
  errorMessage: null,
};

export function recorderReducer(state, action) {
  switch (action.type) {
    case "request":
      return { ...state, status: "requesting", errorMessage: null, errorCode: null };

    case "requestDenied":
      return {
        ...INITIAL_RECORDER_STATE,
        status: "error",
        errorMessage: action.message,
      };

    case "started":
      return { ...state, status: "recording" };

    case "pause":
      return state.status === "recording" ? { ...state, status: "paused" } : state;

    case "resume":
      return state.status === "paused" ? { ...state, status: "recording" } : state;

    case "stop":
      // idempotencyKey is minted once here and stays stable across every
      // retry of *this* recording, so a client retry after a timeout
      // reuses the same key instead of risking a double-billed duplicate.
      return {
        ...state,
        status: "stopped",
        blob: action.blob,
        mimeType: action.mimeType,
        idempotencyKey: action.idempotencyKey,
        estimatedDurationSeconds: action.estimatedDurationSeconds,
      };

    case "discard":
      return { ...INITIAL_RECORDER_STATE };

    case "upload":
      return state.blob ? { ...state, status: "uploading", errorMessage: null, errorCode: null } : state;

    case "uploaded":
      return { ...state, status: "uploading", path: action.path };

    case "uploadFailed":
      return { ...state, status: "error", errorCode: action.code, errorMessage: action.message };

    case "processed":
      return { ...state, status: "review", result: action.result };

    case "retry":
      // Only meaningful from "error", and only if there's still a blob
      // to retry with — otherwise there's nothing to do but discard.
      return state.blob ? { ...state, status: "uploading", errorMessage: null, errorCode: null } : state;

    case "save":
      return { ...state, status: "saving" };

    case "saveFailed":
      return { ...state, status: "review", errorMessage: action.message };

    case "saved":
      return { ...INITIAL_RECORDER_STATE, status: "done" };

    case "reset":
      return { ...INITIAL_RECORDER_STATE };

    default:
      return state;
  }
}
