/** True when the signed-in user hasn't accepted the current consent wording. */
export function needsConsent(meta, version = AI_CONSENT_VERSION) {
  const consent = meta && meta.aiConsent;
  if (!consent) return true;
  return (consent.version || 0) < version;
}

/** Patch to merge into `data.meta` when the user accepts. */
export function buildConsentPatch(version = AI_CONSENT_VERSION, nowISO = () => new Date().toISOString()) {
  return { aiConsent: { version, acceptedAt: nowISO() } };
}

/* ---------- the idempotency key ----------

   Must be a real UUID. `ai_notes_requests.idempotency_key` is typed
   `uuid`, so anything else is rejected by Postgres with 22P02 (invalid
   input syntax) and the recording never gets processed.

   This is deliberately NOT the planner's `uid()` helper, which mints
   short ids like "msn0duf5-hk684" for notes and pages. Those are stored
   in the user's own JSON blob where the format doesn't matter; this one
   crosses into a typed database column where it does. Using uid() here
   is exactly the bug this replaces.
   ------------------------------------------ */

const UUID_HEX = "0123456789abcdef";

/**
 * A v4 UUID.
 *
 * `crypto.randomUUID` is the right answer where it exists, but it is
 * absent in non-secure contexts and on older WebKit — which is precisely
 * where this app runs once it's wrapped in an iOS or Android WebView, and
 * the hardest place to notice a bad value. So the fallbacks matter, and
 * every one of them must produce a genuinely well-formed UUID: a
 * fallback that returns some other random string would reintroduce the
 * 22P02 failure on exactly the platforms that are hardest to debug.
 *
 * `cryptoObj` is injected so the fallback paths are testable.
 */
export function newIdempotencyKey(cryptoObj = typeof globalThis !== "undefined" ? globalThis.crypto : undefined) {
  if (cryptoObj && typeof cryptoObj.randomUUID === "function") {
    return cryptoObj.randomUUID();
  }

  const bytes = new Uint8Array(16);
  if (cryptoObj && typeof cryptoObj.getRandomValues === "function") {
    // Available in non-secure contexts and much older browsers than
    // randomUUID, so this covers most of the gap.
    cryptoObj.getRandomValues(bytes);
  } else {
    // Last resort. Weaker randomness, but an idempotency key only has to
    // be unique per recording, not unguessable.
    for (let i = 0; i < 16; i++) bytes[i] = Math.floor(Math.random() * 256);
  }

  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // variant 1 (RFC 4122)

  let out = "";
  for (let i = 0; i < 16; i++) {
    if (i === 4 || i === 6 || i === 8 || i === 10) out += "-";
    out += UUID_HEX[bytes[i] >> 4] + UUID_HEX[bytes[i] & 0x0f];
  }
  return out;
}

/* ---------- recording format ---------- */

// Speech doesn't need music-quality bitrate. 32kbps keeps a 3-hour
// recording to ~43.2MB — well under Supabase Storage's 50MB/file
// free-tier ceiling. If this changes, the Edge Function's
// MAX_BODY_BYTES (supabase/functions/ai-notes/config.ts) must change
// with it, since that constant assumes this bitrate.
export const RECORDER_AUDIO_BITS_PER_SECOND = 32000;

// Display-only hint for the "X of Y minutes used" badge and the
// near-cap warning banner. The real limit is enforced server-side
// (supabase/functions/ai-notes/config.ts MONTHLY_MINUTES_LIMIT) — if
// this drifts out of sync with that constant it's a cosmetic issue,
// not a security one, since the server never trusts the client's copy.
export const MONTHLY_MINUTES_LIMIT_HINT = 300;

const CANDIDATE_MIME_TYPES = [
  { mimeType: "audio/webm;codecs=opus", extension: "webm" },
  { mimeType: "audio/webm", extension: "webm" },
  { mimeType: "audio/mp4", extension: "m4a" },
  { mimeType: "audio/aac", extension: "aac" },
];

/**
 * Picks the first mime type the platform's MediaRecorder actually
 * supports. `isSupportedFn` is injected (defaults to the real
 * `MediaRecorder.isTypeSupported`) so this is testable in Node,
 * where no MediaRecorder exists at all.
 */
export function pickSupportedMimeType(isSupportedFn) {
  const isSupported =
    isSupportedFn || (typeof MediaRecorder !== "undefined" && MediaRecorder.isTypeSupported.bind(MediaRecorder));
  if (!isSupported) return null;
  for (const candidate of CANDIDATE_MIME_TYPES) {
    if (isSupported(candidate.mimeType)) return candidate;
  }
  return null;
}

/* ---------- error messages ---------- */

/** Maps a getUserMedia/MediaRecorder DOMException to a friendly sentence. */
export function describeRecorderError(err) {
  const name = (err && err.name) || "";
  switch (name) {
    case "NotAllowedError":
    case "PermissionDeniedError":
      return "Microphone access was denied. Please allow microphone access in your browser or device settings to record a lecture.";
    case "NotFoundError":
    case "DevicesNotFoundError":
      return "No microphone was found on this device.";
    case "NotReadableError":
    case "TrackStartError":
      return "Your microphone is being used by another app. Close other apps that might be using it and try again.";
    default:
      return "Something went wrong accessing the microphone. Please try again.";
  }
}

// Codes in this set mean retrying with the same recording would fail
// identically (the provider rejected it outright, not a transient
// hiccup) — the UI uses this to withhold the "Try again" option, since
// offering it would just strand the user in a loop.
export const PERMANENT_FAILURE_CODES = new Set([
  "recording_too_long",
  "transcription_too_long",
  // The key is minted once and reused across retries, so a malformed one
  // fails identically every time — the fix is reloading, not retrying.
  "bad_idempotency_key",
]);

const ERROR_MESSAGES = {
  no_access: "AI notes isn't enabled for your account yet.",
  usage_exceeded: "You've used all your AI minutes for this month.",
  already_processing: "This recording is already being processed — try again shortly.",
  recording_too_long: "Recordings are limited to about 3 hours.",
  recording_missing: "We couldn't find that recording — please record it again.",
  transcription_failed: "We couldn't transcribe that recording. Please try again.",
  transcription_too_long: "This recording is too long to process — try recording in shorter segments.",
  unauthenticated: "Please sign in again to use AI notes.",
  // Only reachable from a stale cached copy of the app: current builds
  // mint a UUID. Telling the user to reload is what actually fixes it.
  bad_idempotency_key: "Please reload the app and try recording again.",
};

/** Maps the ai-notes Edge Function's JSON error body to a friendly sentence. */
export function parseAiNotesError(json, status) {
  const code = json && json.code;
  if (code && ERROR_MESSAGES[code]) return ERROR_MESSAGES[code];
  if (json && json.error) return json.error;
  return `Something went wrong (${status || "network error"}). Please try again.`;
}

